#!/usr/bin/env python3
"""Check mechanical Verus-to-Lean links in a disposable Lake package."""

import argparse
import json
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

from mappings import ENUMS, SHAPES
from stream_wal import generated_publication
from translate import Emitter, Parser, Unsupported, declarations, postcondition


LINK = Path(__file__).resolve().parent
ROOT = LINK.parent.parent
SPECS = json.loads((LINK / "specs.json").read_text())
HEADER = """-- Generated by verification/link/run.py.
import Logkeeper.Generated.Bridge

set_option warningAsError true
set_option autoImplicit false
set_option linter.unusedVariables false

namespace Logkeeper.Generated
noncomputable section
open Classical
"""

GENERATED = "Logkeeper/Generated"
EQUIVALENCES = f"{GENERATED}/Equivalences.lean"
COVERAGE_ROW = re.compile(r"^\| `([^ `]+\.rs)` \| `(\w+)` \| (.+) \| (.+) \|$", re.M)
THEOREM = re.compile(r"^theorem (link_\w+)\b", re.M)


def bindings():
    for area, files in SPECS.items():
        for path, names in files.items():
            for name, reference in names.items():
                yield area, path, name, reference


def source(path, replacements):
    return replacements[path] if path in replacements else (ROOT / path).read_text()


def generate(replacements=None):
    replacements = replacements or {}
    out = [HEADER]
    for area, files in SPECS.items():
        functions = {}
        for path, names in files.items():
            tokens, found = declarations(source(path, replacements))
            for name in names:
                if name not in found:
                    raise Unsupported(f"{path}: missing definition {name}")
                if name in functions:
                    raise Unsupported(f"{area}: ambiguous spec name {name}")
                is_spec, offset, line = found[name]
                try:
                    spec = (Parser(tokens[offset:], path).definition() if is_spec
                            else postcondition(tokens, offset, path))
                    functions[name] = path, spec
                except Unsupported as error:
                    raise Unsupported(f"{path}:{line}: {name}: {error}") from error
        emitter = Emitter({name: spec for name, (_, spec) in functions.items()}, SHAPES, ENUMS)
        out.append(f"\nnamespace {area}\n")
        for path, spec in functions.values():
            out.append(f"-- {path}:{spec.line}")
            try:
                out.append(emitter.definition(spec))
            except Unsupported as error:
                raise Unsupported(f"{path}:{spec.line}: {spec.name}: {error}") from error
        out.append(f"end {area}\n")
    out.append(generated_publication(lambda path: source(path, replacements)))
    out.append("end\nend Logkeeper.Generated\n")
    return "\n".join(out)


def audit_source():
    """Require a decision for every law and spec in each proof harness."""
    rows = {}
    for path, name, reference, status in COVERAGE_ROW.findall((LINK / "inventory.md").read_text()):
        if (path, name) in rows:
            raise ValueError(f"duplicate inventory row for {path}: {name}")
        rows[path, name] = reference, status

    linked = {(path, name): reference for _, path, name, reference in bindings()}
    sources = {path for path, _ in linked} | {path for path, _ in rows}
    sources |= {str(path.relative_to(ROOT)) for path in (ROOT / "verification/verus").glob("*/*.rs")
                if path.name in {"laws.rs", "proof.rs"}}
    required = set(linked)
    for path in sorted(sources):
        _, rust = declarations((ROOT / path).read_text())
        if Path(path).name in {"laws.rs", "proof.rs"}:
            required |= {(path, name) for name in rust if name != "main"}
        for row_path, name in rows:
            if row_path == path and name not in rust:
                raise ValueError(f"stale inventory row for {path}: {name}")

    missing = sorted(required - rows.keys())
    if missing:
        raise ValueError("missing inventory rows:\n" + "\n".join(f"  {p}: {n}" for p, n in missing))

    for (path, name), (reference, status) in rows.items():
        expected = linked.get((path, name))
        if expected is not None and (reference != f"`{expected}`" or status != "Equivalence"):
            raise ValueError(f"{path}: {name}: inventory disagrees with specs.json")
        if expected is None and status == "Equivalence":
            raise ValueError(f"{path}: {name}: equivalence is absent from specs.json")
    return sum(Path(path).name in {"laws.rs", "proof.rs"} for path, _ in rows)


def audit_module():
    """Require real theorems whose statements link the two named definitions."""
    lines = [
        "import Logkeeper.Generated.Equivalences",
        "import Lean",
        "open Lean Elab Command",
        "private def checkLink (proof generated reference : Name) : CommandElabM Unit := do",
        "  let some (.thmInfo info) := (← getEnv).find? proof",
        '    | throwError "missing theorem {proof}"',
        "  let uses := info.type.getUsedConstantsAsSet",
        "  unless uses.contains generated && uses.contains reference do",
        '    throwError "wrong definitions in statement of {proof}"',
        "  let axioms ← collectAxioms proof",
        "  let allowed := [``propext, ``Classical.choice, ``Quot.sound]",
        "  unless axioms.all (allowed.contains ·) do",
        '    throwError "nonstandard axiom in {proof}: {axioms}"',
    ]
    count = 0
    for area, _, name, reference in bindings():
        if reference is None:
            continue
        count += 1
        proof = f"Logkeeper.Generated.{area}.link_{name}"
        generated = f"Logkeeper.Generated.{area}.{name}"
        lines.append(f"run_cmd checkLink ``{proof} ``{generated} ``{reference}")
    lines.append("run_cmd checkLink ``Logkeeper.Generated.stream_wal.link_publication "
                 "``Logkeeper.Generated.stream_wal.publication ``Logkeeper.StreamWAL.PublicationOrder")
    count += 1
    return "\n".join(lines) + "\n", count


def run(lake, package, *args):
    return subprocess.run([lake, *args], cwd=package, text=True, capture_output=True, check=False)


def build(lake, package, target):
    result = run(lake, package, "build", target)
    if result.returncode:
        raise ValueError(result.stdout + result.stderr)


def replace_once(value, old, new, label):
    if not old or old == new or value.count(old) != 1:
        raise ValueError(f"{label}: mutation must change exactly one occurrence")
    return value.replace(old, new, 1)


def theorem_range(name, area, contents):
    match = re.search(
        rf"^namespace {re.escape(area)}\n(?:(?!^end {re.escape(area)}$)[\s\S])*?"
        rf"^theorem {re.escape(name)}\b[\s\S]*?(?=^theorem |^end {re.escape(area)}$)",
        contents, re.M,
    )
    if match is None:
        raise ValueError(f"could not locate {area}.{name}")
    start = contents.index(f"theorem {name}", match.start(), match.end())
    return contents.count("\n", 0, start) + 1, contents.count("\n", 0, match.end()) + 1


def reject_at(lake, package, area, theorem, equivalences):
    # First verify that the mutated source and all prerequisites still elaborate.
    build(lake, package, "Logkeeper.Generated.Verus")
    result = run(lake, package, "env", "lean", "--json", EQUIVALENCES)
    start, stop = theorem_range(theorem, area, equivalences)
    messages = [json.loads(line) for line in result.stdout.splitlines()]
    errors = [m for m in messages if m["severity"] == "error"]
    if (result.returncode == 0 or not errors or result.stderr or
            not all(Path(m["fileName"]).name == "Equivalences.lean" and
                    start <= m["pos"]["line"] < stop and
                    m["data"].startswith(("unsolved goals", "Tactic `", "Type mismatch",
                                               "'change' tactic failed", "omega could not prove the goal"))
                    for m in errors)):
        raise ValueError(f"expected rejection only at {area}.{theorem}\n{result.stdout}{result.stderr}")


def check_controls(lake, package, baseline, equivalences):
    verus_module = package / GENERATED / "Verus.lean"
    controls = json.loads((LINK / "controls.json").read_text())
    for control in controls:
        path = control["file"]
        mutated = (ROOT / path).read_text()
        for edit in control.get("edits", [control]):
            mutated = replace_once(mutated, edit["find"], edit["replace"], control["name"])
        if path.startswith("verification/lean/"):
            target = package / Path(path).relative_to("verification/lean")
            target.write_text(mutated)
        else:
            target = verus_module
            target.write_text(generate({path: mutated}))
        try:
            reject_at(lake, package, control["area"], control["theorem"], equivalences)
        finally:
            target.write_text(baseline if target == verus_module else (ROOT / path).read_text())
        print(f'{control["name"]}: rejected at {control["area"]}.{control["theorem"]}', flush=True)
    return len(controls)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--emit", action="store_true", help="write the generated definitions to stdout")
    parser.add_argument("--lake", default=str(Path.home() / ".elan/bin/lake"))
    args = parser.parse_args()
    verus = generate()
    if args.emit:
        print(verus, end="")
        return
    inventory_count = audit_source()
    audit, count = audit_module()
    equivalences = (LINK / "Equivalences.lean").read_text()
    with tempfile.TemporaryDirectory(prefix="logkeeper-link-") as tmp:
        package = Path(tmp) / "lean"
        shutil.copytree(ROOT / "verification/lean", package,
                        ignore=shutil.ignore_patterns(".lake", ".results", "__pycache__"))
        module = package / GENERATED
        module.mkdir(exist_ok=True)
        shutil.copyfile(LINK / "Bridge.lean", module / "Bridge.lean")
        (module / "Verus.lean").write_text(verus)
        (module / "Equivalences.lean").write_text(equivalences)
        (module / "Audit.lean").write_text(audit)
        build(args.lake, package, "Logkeeper.Generated.Audit")
        print(f"Baseline: {count} equivalences passed the kernel and axiom audit", flush=True)
        negatives = check_controls(args.lake, package, verus, equivalences)
    print(f"{count} equivalences and {negatives} controls passed; {inventory_count} harness declarations inventoried")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError) as error:
        raise SystemExit(str(error)) from error
